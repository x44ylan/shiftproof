  await page.locator('.metrics').scrollIntoViewIfNeeded();
  await caption('One revision. Two consequences.', 'The revised rota has one uncovered duty and one double booking. Four shifts changed between the two versions.');
  await page.locator('.shift-row[data-shift-id="welcome"]').click();
  await page.locator('#shift-detail').scrollIntoViewIfNeeded();
