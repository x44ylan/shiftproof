  await page.locator('.shift-row[data-shift-id="donations"]').click();
  await page.locator('#assignment-list').getByLabel('Alex',{exact:true}).check();
  await page.locator('#apply-assignment').click();
  await page.locator('.metrics').scrollIntoViewIfNeeded();
